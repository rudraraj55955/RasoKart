import { test } from "node:test";
import assert from "node:assert/strict";
import pg from "pg";
import { getIsolatedWhiteLabelTestDatabaseUrl } from "../lib/whiteLabelPgTestSafety";

test("PostgreSQL: tenant-scoped concurrent reservations and financial transition", async () => {
  const url = getIsolatedWhiteLabelTestDatabaseUrl(process.env);
  const pool = new pg.Pool({ connectionString: url, max: 12 });
  try {
    const name = "wl_test_finance_commands";
    // Dedicated TEST database only, separate table namespace from production schemas.
    await pool.query(`CREATE TABLE IF NOT EXISTS ${name} (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id integer NOT NULL, merchant_id integer NOT NULL,
      operation text NOT NULL, idempotency_key text NOT NULL,
      payload_hash text NOT NULL, status text NOT NULL DEFAULT 'reserved',
      UNIQUE (tenant_id, merchant_id, operation, idempotency_key)
    )`);
    await pool.query(`TRUNCATE TABLE ${name} RESTART IDENTITY`);
    const key = "test-concurrent-request-123";
    const reserve = (tenantId: number, merchantId: number, hash = "aaa") =>
      pool.query(`INSERT INTO ${name} (tenant_id,merchant_id,operation,idempotency_key,payload_hash)
      VALUES ($1,$2,'wallet_adjustment',$3,$4) ON CONFLICT DO NOTHING RETURNING id`,
      [tenantId, merchantId, key, hash]);
    const duplicates = await Promise.all(Array.from({ length: 20 }, () => reserve(1, 5)));
    assert.equal(duplicates.filter(x => x.rowCount === 1).length, 1, "exactly one reservation wins");
    assert.equal((await pool.query(`SELECT count(*)::int AS count FROM ${name} WHERE tenant_id=1`)).rows[0].count, 1);
    assert.equal((await reserve(2, 5)).rowCount, 1, "different tenant isolated");
    assert.equal((await reserve(1, 6)).rowCount, 1, "different merchant isolated");
    assert.equal((await reserve(1, 5, "changed")).rowCount, 0, "conflicting payload cannot reserve duplicate");
    const winner = await pool.query(`UPDATE ${name} SET status='completed'
      WHERE tenant_id=1 AND merchant_id=5 AND status='reserved' RETURNING id`);
    assert.equal(winner.rowCount, 1);
    const repeat = await pool.query(`UPDATE ${name} SET status='completed'
      WHERE tenant_id=1 AND merchant_id=5 AND status='reserved' RETURNING id`);
    assert.equal(repeat.rowCount, 0, "completion cannot execute twice");
    const crossTenant = await pool.query(`UPDATE ${name} SET status='failed'
      WHERE tenant_id=99 AND merchant_id=5 AND status='reserved' RETURNING id`);
    assert.equal(crossTenant.rowCount, 0, "wrong tenant cannot complete");
  } finally {
    await pool.end();
  }
});
